(* The global protection table (GitHub issue #1012 slice 1).

   `--facts DIR` writes one TSV row per `let mut` global of the
   program, with the protection its declared type shows. The ratchet
   scripts/buildcheck_global_protection.py reads it, so the classification
   is the compiler's view of the type (registries, generic templates,
   protocol-generated owners) rather than a regular expression over .tkb
   text. docs/GLOBAL_PROTECTION.md is the format's contract.

   A type's protection, in the order tried:

   - `[T; N]`: the protection of T (an array of protected cells);
   - `AtomicWord` -> atomic;
   - `LockedCell(T)`, `RegionPool(T)` (generated as `RegionPool__T`) -> lock;
   - `Place(T)` -> place;  `BootOnce(T)` -> boot_once (#1013);
   - a `struct per_cpu` store -> per_cpu;
   - a `struct dma_fixed` record -> dma_fixed;
   - a struct generated by a `protocol` declaration -> protocol;
   - a plain struct with at least one field, every field of which is
     protected or declared `guarded_by(L)` -> composite (Mutex, TaskMutex
     and the lock words are this: one AtomicWord);
   - anything else -> none.

   A `region let mut` backing is `region` whatever its element type. *)

open Ast

let format_version = 3

let columns = [ "file"; "line"; "name"; "visibility"; "qualifier"; "type"; "protection" ]

let rec spell = function
  | TypeBool -> "bool" | TypeI8 -> "i8" | TypeI16 -> "i16" | TypeI32 -> "i32"
  | TypeI64 -> "i64" | TypeU8 -> "u8" | TypeU16 -> "u16" | TypeU32 -> "u32"
  | TypeU64 -> "u64" | TypeU16Be -> "u16be" | TypeU32Be -> "u32be"
  | TypeIsize -> "isize" | TypeUsize -> "usize" | TypeVoid -> "void"
  | TypePtr t -> "*" ^ spell t
  | TypeIo t -> "io " ^ spell t
  | TypeArray (t, n) -> Printf.sprintf "[%s;%d]" (spell t) n
  | TypeArraySym (t, _) -> Printf.sprintf "[%s;N]" (spell t)
  | TypeNamed n | TypeIndexed (n, _) | TypeView (n, _) -> n
  | TypeVariant (n, _, _) -> n
  | TypeGenericInst (n, args) ->
      n ^ "(" ^ String.concat "," (List.map spell args) ^ ")"
  | TypeRefined (lo, hi, t) -> Printf.sprintf "{%d..<%d as %s}" lo hi (spell t)
  | TypeMultiple (_, t) | TypeSingleton (t, _) -> spell t
  | TypeExists (_, _, t) -> "exists." ^ spell t
  | TypeTuple ts -> "(" ^ String.concat "," (List.map spell ts) ^ ")"
  | TypeFn _ -> "fn"
  | _ -> "?"

let write_table (out : out_channel) (prog : toplevel list) =
  (* Plain struct fields by name, and the structs a protocol generated. *)
  let fields = Hashtbl.create 256 and protocol = Hashtbl.create 16 in
  List.iter (function
    | StructDef (name, fs, _, _, _, loc) ->
        Hashtbl.replace fields name fs;
        if String.starts_with ~prefix:Device_protocol_registry.prefix
             (source_file_of_loc loc)
        then Hashtbl.replace protocol name ()
    | OwnedStructDef (name, _, _, fs, _, _, _, _, loc) ->
        Hashtbl.replace fields name fs;
        if String.starts_with ~prefix:Device_protocol_registry.prefix
             (source_file_of_loc loc)
        then Hashtbl.replace protocol name ()
    | _ -> ()) prog;
  let rec protection seen = function
    | TypeArray (t, _) | TypeArraySym (t, _) | TypeMultiple (_, t)
    | TypeExists (_, _, t) -> protection seen t
    | TypeGenericInst (("LockedCell" | "RegionPool"), _) -> "lock"
    | TypeGenericInst ("Place", _) | TypeVariant ("Place", _, _) -> "place"
    | TypeGenericInst ("BootOnce", _) -> "boot_once"
    | TypeNamed n | TypeIndexed (n, _) -> named seen n
    | _ -> "none"
  and named seen n =
    if n = "AtomicWord" then "atomic"
    (* region(T) pools are generated under this prefix (Region_builtin). *)
    else if String.starts_with ~prefix:"RegionPool__" n then "lock"
    else if Per_cpu_registry.is_store n then "per_cpu"
    else if Dma_fixed_registry.is_fixed n then "dma_fixed"
    else if Hashtbl.mem protocol n then "protocol"
    else if List.mem n seen then "none"
    else match Hashtbl.find_opt fields n with
      | Some ((_ :: _) as fs)
        when List.for_all (fun (f, t) ->
               Guarded_registry.lock_of n f <> None
               || protection (n :: seen) t <> "none") fs -> "composite"
      | _ -> "none"
  in
  Printf.fprintf out "# takibi globals, format %d; see docs/GLOBAL_PROTECTION.md\n"
    format_version;
  output_string out (String.concat "\t" columns ^ "\n");
  List.iter (function
    | LetDef (name, ty, _, _, true, priv, loc) ->
        let ty = Option.value ty ~default:TypeVoid in
        let qualifier =
          if Region_backing.is_marked name then "region"
          else if Init_state.is_scratch name then "scratch" else "-" in
        let prot = if qualifier = "region" then "region" else protection [] ty in
        Printf.fprintf out "%s\t%d\t%s\t%s\t%s\t%s\t%s\n"
          (Call_graph.relative (source_file_of_loc loc)) loc.Lexing.pos_lnum name
          (if priv then "private" else "public") qualifier (spell ty) prot
    | _ -> ()) prog

(* GitHub issue #769: every use of a global, as a second table of the same
   file (no new flag: facts, not flags, #1027/#987). One row per use, after
   name binding: a function's parameters and locals (let, let-match, for,
   for-each, tuple and match bindings) shadow a global of the same name for
   the rest of their scope, so a row is a use of the global itself. The
   kind is the innermost one that applies:

   - `write`   the root of an assignment's target (`g = ..`, `g.f = ..`,
               `g[i] = ..`);
   - `atomic_store` `&g..` given to a whole-statement atomic_word_store,
               atomic_word_fetch_add or atomic_word_fetch_sub: it writes and
               nothing sees the old value;
   - `atomic_load` `&g..` given to atomic_word_load: it reads and cannot write;
   - `address` any other root of `&g`, `&g.f`, `&g[i]`;
   - `load`    a read that yields no pointer into `g` (GitHub issue #1275): a
               field or element path of scalar type (`g.f`, `g[i]`, `g[i].f`),
               an operand of slice_eq, or a cast to a const slice;
   - `region`  the operand of a region claim (`region_of(g)`);
   - `index`   the base of an index or slice (`g[i]`, `g[a..<b]`);
   - `cast`    the operand of a cast (`g as T`);
   - `read`    any other use, including `g(x)`, a call through a global
               function pointer.

   A global's initializer that names another global is a use in function
   `-`. Uses inside a generic template are reported at the template. *)

let uses_columns = [ "file"; "line"; "name"; "kind"; "function" ]

module S = Set.Make (String)

let write_uses (out : out_channel) (prog : toplevel list) =
  let globals = List.fold_left (fun acc -> function
    | LetDef (name, _, _, _, _, _, _) -> S.add name acc
    | _ -> acc) S.empty prog in
  let row fn (e : expr) name kind =
    Printf.fprintf out "%s\t%d\t%s\t%s\t%s\n"
      (Call_graph.relative (source_file_of_loc e.loc)) e.loc.Lexing.pos_lnum
      name kind fn in
  let rec root (e : expr) = match e.desc with
    | Var n -> Some (n, e)
    | FieldGet (b, _) | Index (b, _) | SliceOf (b, _, _) -> root b
    | _ -> None in
  (* Declared types, to tell a scalar path from one that decays to a pointer.
     Anything not resolved here (a generic field, a named alias) stays `read`,
     the weaker claim. Parameters of a generic struct are not resolved. *)
  let global_types = List.fold_left (fun acc -> function
    | LetDef (name, Some ty, _, _, _, _, _) -> (name, ty) :: acc
    | _ -> acc) [] prog in
  let struct_fields = List.filter_map (function
    | StructDef (name, fs, _, _, _, _)
    | OwnedStructDef (name, _, _, fs, _, _, _, _, _) -> Some (name, fs)
    | _ -> None) prog in
  let rec strip = function
    | TypeRefined (_, _, t) | TypeMultiple (_, t) | TypeSingleton (t, _) -> strip t
    | t -> t in
  let rec path_type (e : expr) = match e.desc with
    | Var n -> List.assoc_opt n global_types
    | FieldGet (b, f) ->
        (match Option.map strip (path_type b) with
         | Some (TypeNamed s | TypePtr (TypeNamed s)) ->
             Option.bind (List.assoc_opt s struct_fields) (List.assoc_opt f)
         | _ -> None)
    | Index (b, _) ->
        (match Option.map strip (path_type b) with
         | Some (TypeArray (t, _) | TypeArraySym (t, _) | TypePtr t | TypeSlice (t, _, _)) ->
             Some t
         | _ -> None)
    | _ -> None in
  let is_scalar_path e = match Option.map strip (path_type e) with
    | Some (TypeBool | TypeI8 | TypeI16 | TypeI32 | TypeI64 | TypeU8 | TypeU16
           | TypeU32 | TypeU64 | TypeU16Be | TypeU32Be | TypeIsize | TypeUsize
           | TypePtr _ | TypeFn _) -> true
    | _ -> false in
  let global_root locals e = match root e with
    | Some (n, v) when S.mem n globals && not (S.mem n locals) -> Some (n, v)
    | _ -> None in
  let rec expr fn locals kind (e : expr) =
    let sub = expr fn locals "read" in
    (* A place rooted at a global that the row itself classifies; its index
       and slice operands are ordinary reads. *)
    let place kind (place : expr) (n, v) =
      row fn v n kind; lvalue_parts fn locals place in
    match e.desc with
    | FieldGet _ | Index _ when is_scalar_path e && global_root locals e <> None ->
        place "load" e (Option.get (global_root locals e))
    | Call ("atomic_word_load", [ { desc = AddrOf inner; _ } ])
      when global_root locals inner <> None ->
        place "atomic_load" inner (Option.get (global_root locals inner))
    | Call ("slice_eq", args) ->
        List.iter (fun (a : expr) ->
          let a = match a.desc with Cast (_, inner) -> inner | _ -> a in
          match global_root locals a with
          | Some g -> place "load" a g
          | None -> sub a) args
    | Cast (TypeSlice (_, _, SliceReadonly), inner) when global_root locals inner <> None ->
        place "load" inner (Option.get (global_root locals inner))
    | Var n ->
        if S.mem n globals && not (S.mem n locals) then row fn e n kind
    | Assign (lhs, rhs) ->
        (match root lhs with
         | Some (n, v) when S.mem n globals && not (S.mem n locals) ->
             row fn v n "write"; lvalue_parts fn locals lhs
         | _ -> sub lhs);
        sub rhs
    | AddrOf inner ->
        (match root inner with
         | Some (n, v) when S.mem n globals && not (S.mem n locals) ->
             row fn v n "address"; lvalue_parts fn locals inner
         | _ -> sub inner)
    | Call ("region_of", [ ({ desc = Var _; _ } as a) ]) ->
        expr fn locals "region" a
    | Call (callee, args) ->
        (* `g(x)` calls through a global function pointer: a read of `g`. A
           local of that name shadows it, as for any other use. *)
        if S.mem callee globals && not (S.mem callee locals) then
          row fn e callee "read";
        List.iter sub args
    | Index (b, i) -> expr fn locals (base_kind b) b; sub i
    | SliceOf (b, lo, hi) -> expr fn locals (base_kind b) b; sub lo; sub hi
    | Cast (_, inner) ->
        (match inner.desc with Var _ -> expr fn locals "cast" inner | _ -> sub inner)
    | FieldGet (b, _) -> expr fn locals kind b
    | VariantCtor (_, _, a) | Bnot a | Deref a | Unsafe a -> sub a
    | BinOp (_, a, b) -> sub a; sub b
    | StructLit es | TupleLit es -> List.iter sub es
    | _ -> ()
  and base_kind (b : expr) = match b.desc with Var _ -> "index" | _ -> "read"
  (* The index and slice operands inside an assigned or addressed place
     are ordinary reads. *)
  and lvalue_parts fn locals (e : expr) =
    let sub = expr fn locals "read" in
    match e.desc with
    | FieldGet (b, _) -> lvalue_parts fn locals b
    | Index (b, i) -> lvalue_parts fn locals b; sub i
    | SliceOf (b, lo, hi) -> lvalue_parts fn locals b; sub lo; sub hi
    | _ -> ()
  and stmts fn locals (ss : stmt list) =
    ignore (List.fold_left (fun locals s -> stmt fn locals s) locals ss)
  and arms fn locals = List.iter (function
    | ArmVariant (_, _, Some (PayloadBind (x, _)), body) ->
        stmts fn (S.add x locals) body
    | ArmVariant (_, _, _, body) | ArmWild body | ArmMiss body
    | ArmIntLit (_, body) | ArmByteSliceLit (_, body) -> stmts fn locals body)
  and stmt fn locals (s : stmt) =
    let e = expr fn locals "read" in
    match s.desc with
    | Expr { desc = Call (("atomic_word_store" | "atomic_word_fetch_add"
                          | "atomic_word_fetch_sub"),
                          { desc = AddrOf inner; _ } :: rest); _ }
      when (match root inner with
            | Some (n, _) -> S.mem n globals && not (S.mem n locals)
            | None -> false) ->
        (match root inner with
         | Some (n, v) -> row fn v n "atomic_store"
         | None -> ());
        lvalue_parts fn locals inner;
        List.iter e rest;
        locals
    | Return (Some x) | Expr x | Yield x | StaticAssert (x, _) -> e x; locals
    | Return None | Break | Continue -> locals
    | Block b | UnsafeBlock b -> stmts fn locals b; locals
    | Let (_, name, _, init, _) -> Option.iter e init; S.add name locals
    | LetTuple (names, init) -> e init; List.fold_left (fun l n -> S.add n l) locals names
    | If (c, a, b) -> e c; stmts fn locals a; stmts fn locals b; locals
    | While (c, b) -> e c; stmts fn locals b; locals
    | For (x, _, lo, hi, b) -> e lo; e hi; stmts fn (S.add x locals) b; locals
    | ForEach (x, it, b) -> e it; stmts fn (S.add x locals) b; locals
    | Match (subject, ms) -> e subject; arms fn locals ms; locals
    | LetMatch (_, name, _, subject, ms) ->
        e subject; arms fn locals ms; S.add name locals
  in
  output_string out "# uses\n";
  output_string out (String.concat "\t" uses_columns ^ "\n");
  List.iter (function
    | FuncDef f ->
        let params = List.fold_left (fun l (p, _) -> S.add p l) S.empty f.params in
        stmts f.name params f.body
    | LetDef (_, _, Some init, _, _, _, _) -> expr "-" S.empty "read" init
    | _ -> ()) prog
