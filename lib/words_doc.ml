(* GitHub issue #1003: WORDS.md, the compiler-owned word inventory as a
   tracked document. `takibi --emit-doc words` prints it and
   `language-words-control` (make langcheck) fails when the tracked file is
   stale, so adding a word is a visible diff, as adding an effect row is a
   diff of EFFECTS.md. Use counts are deliberately absent: they move with
   every commit and would turn the freshness check into noise. *)

let code s = "`" ^ s ^ "`"

let builtin_kind name =
  if List.mem name Language_words.removed_builtins then
    "removed (diagnostic only; #1004)"
  else if List.mem name Device_protocol_registry.builtins then
    "generated-only (device protocol wrappers; #1004)"
  else if List.mem name Language_words.instruction_builtins then
    "instruction"
  else if List.mem name Atomic_spec.names
       || List.mem_assoc name Atomic_spec.cell_ops then
    "atomic (atomic_spec.ml)"
  else "general"

let markdown () =
  let b = Buffer.create 8192 in
  let p fmt = Printf.bprintf b fmt in
  p "<!-- GENERATED by takibi --emit-doc words. Do not edit. -->\n\n";
  p "# Compiler-owned words\n\n";
  p "The complete inventory of source words the compiler gives a meaning, \
     generated from `lib/language_words.ml`. SPEC.md \"Compiler-Owned Words \
     and Names\" defines the classes.\n\n";
  p "## Hard keywords (%d)\n\n" (List.length Language_words.classified_hard_keywords);
  p "| Keyword | Class |\n| --- | --- |\n";
  List.iter (fun (w, c) ->
    p "| %s | %s |\n" (code w) (Language_words.keyword_class_name c))
    Language_words.classified_hard_keywords;
  p "\n## Contextual keywords (%d)\n\n" (List.length Language_words.contextual_keywords);
  p "| Keyword |\n| --- |\n";
  List.iter (fun w -> p "| %s |\n" (code w)) Language_words.contextual_keywords;
  p "\n## Compiler builtins (%d)\n\n" (List.length Language_words.compiler_builtins);
  p "| Builtin | Kind |\n| --- | --- |\n";
  List.iter (fun w -> p "| %s | %s |\n" (code w) (builtin_kind w))
    Language_words.compiler_builtins;
  p "\n## Compiler-owned types (%d)\n\n" (List.length Language_words.compiler_owned_types);
  p "| Type | Owner |\n| --- | --- |\n";
  List.iter (fun (w, m) -> p "| %s | `lib/%s` |\n" (code w) m)
    Language_words.compiler_owned_types;
  p "\n## Compiler-owned functions (%d)\n\n" (List.length Language_words.compiler_owned_functions);
  p "| Function | Owner |\n| --- | --- |\n";
  List.iter (fun (w, m) -> p "| %s | `lib/%s` |\n" (code w) m)
    Language_words.compiler_owned_functions;
  p "\n## Declaration qualifiers (%d)\n\n" (List.length Language_words.declaration_qualifiers);
  p "| Form | Recorded by |\n| --- | --- |\n";
  List.iter (fun (w, m) -> p "| %s | %s |\n" (code w) m)
    Language_words.declaration_qualifiers;
  p "\n## Predeclared names and checker intrinsics\n\n";
  p "| Name | Class |\n| --- | --- |\n";
  List.iter (fun w -> p "| %s | predeclared name |\n" (code w)) Language_words.predeclared_names;
  List.iter (fun w -> p "| %s | checker intrinsic |\n" (code w)) Language_words.checker_intrinsics;
  Buffer.contents b
