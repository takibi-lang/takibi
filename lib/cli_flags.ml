(* GitHub issue #1027 step 1: the compiler's command line as a table.
   bin/main.ml declares one row per flag; [parse] is the only argv reader
   and [markdown] writes CLI.md (takibi --generate cli), which
   cli-flags-control keeps fresh. The groups follow #1027's census. *)

type group =
  | Target_output
  | Codegen
  | Policy
  | Facts
  | Generated
  | Development

let group_name = function
  | Target_output -> "target and output"
  | Codegen -> "codegen"
  | Policy -> "policy gates"
  | Facts -> "facts for build checks"
  | Generated -> "generated sources"
  | Development -> "compiler development"

let groups = [Target_output; Codegen; Policy; Facts; Generated; Development]

type handler =
  | No_arg of (unit -> unit)
  | Arg of (string -> unit)
  (* A closed set of kinds; a kind paired with [Some meta] takes one more
     argument (`--generate tla <dir>`). *)
  | Choice of (string * string option) list * (string -> string option -> unit)

type t = {
  name : string;
  group : group;
  (* Metavariable shown in the table, and the noun phrase of the
     missing-argument error ("requires a path"). *)
  arg : (string * string) option;
  help : string;
  handler : handler;
}

let flag name group ?arg handler help =
  (match arg, handler with
   | Some _, Arg _ | None, No_arg _ | None, Choice _ -> ()
   | _ -> invalid_arg ("Cli_flags.flag: argument shape of " ^ name));
  { name; group; arg; help; handler }

let is_flag_like s = String.length s > 1 && s.[0] = '-'

(* Input files in command-line order, or the first error. *)
let parse flags args =
  let rec go files = function
    | [] -> Ok (List.rev files)
    | a :: rest ->
        (match List.find_opt (fun f -> f.name = a) flags with
         | Some { handler = No_arg h; _ } -> h (); go files rest
         | Some { handler = Choice (kinds, h); _ } ->
             let names = String.concat ", " (List.map (fun (k, _) -> "'" ^ k ^ "'") kinds) in
             (match rest with
              | k :: rest when List.mem_assoc k kinds ->
                  (match List.assoc k kinds, rest with
                   | None, rest -> h k None; go files rest
                   | Some _, v :: rest -> h k (Some v); go files rest
                   | Some meta, [] -> Error (Printf.sprintf "%s %s requires %s" a k meta))
              | _ -> Error (Printf.sprintf "%s requires one of %s" a names))
         | Some { handler = Arg h; arg; _ } ->
             (match rest with
              | v :: rest -> h v; go files rest
              | [] ->
                  let noun = match arg with Some (_, n) -> n | None -> "an argument" in
                  Error (Printf.sprintf "%s requires %s" a noun))
         | None when is_flag_like a ->
             Error (Printf.sprintf "unknown flag '%s' (see CLI.md)" a)
         | None -> go (a :: files) rest)
  in
  go [] args

let choice_meta kinds =
  String.concat "|" (List.map (function
    | k, None -> k
    | k, Some meta -> k ^ " " ^ meta) kinds)

let meta f = match f.arg, f.handler with
  | Some (m, _), _ -> Some m
  | None, Choice (kinds, _) -> Some (choice_meta kinds)
  | None, _ -> None

let usage flags =
  "<filename>... "
  ^ String.concat " " (List.map (fun f ->
      match meta f with
      | None -> Printf.sprintf "[%s]" f.name
      | Some m -> Printf.sprintf "[%s %s]" f.name m) flags)

(* [facts]: the files `--facts DIR` writes, name and content, from the
   one table in bin/main.ml. *)
let markdown ~facts flags =
  let b = Buffer.create 4096 in
  let p fmt = Printf.bprintf b fmt in
  p "<!-- GENERATED by takibi --generate cli. Do not edit. -->\n\n";
  p "# Compiler command line\n\n";
  p "`takibi <file.tkb>... [flags]`: %d flags, from the table in \
     `bin/main.ml`. GitHub issue #1027 plans their consolidation.\n" (List.length flags);
  List.iter (fun g ->
    match List.filter (fun f -> f.group = g) flags with
    | [] -> ()
    | rows ->
        p "\n## %s (%d)\n\n" (String.capitalize_ascii (group_name g)) (List.length rows);
        p "| Flag | Argument | Meaning |\n| --- | --- | --- |\n";
        List.iter (fun f ->
          p "| `%s` | %s | %s |\n" f.name
            (match meta f with
             | Some m ->
                 (* A table cell needs '|' escaped, even inside code. *)
                 "`" ^ String.concat "\\|" (String.split_on_char '|' m) ^ "`"
             | None -> "-")
            f.help) rows) groups;
  p "\n## Fact files (%d)\n\n" (List.length facts);
  p "`--facts DIR` writes every one of these, under these names.\n\n";
  p "| File | Content |\n| --- | --- |\n";
  List.iter (fun (name, what) -> p "| `%s` | %s |\n" name what) facts;
  Buffer.contents b
